#!/usr/bin/env node
/**
 * Bundles the Iconify icons the app uses into src/lib/icons.generated.js so @iconify/react never calls
 * api.iconify.design / api.unisvg.com / api.simplesvg.com at runtime (third-party requests that leak which UI
 * is open and that the Content-Security-Policy forbids). Re-run after adding an icon:  npm run icons
 * Needs the matching `@iconify-json/<prefix>` dev dependency for every prefix used.
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, "$1")), "..");
const require = createRequire(path.join(root, "package.json"));
const SRC_DIRS = ["features", "ui", "layout", "lib", "helper"]; // the routed app (template demo pages are not bundled)
const NOT_ICON_PREFIX = /^(http|https|data|blob|tel|mailto|ws|wss|javascript|forksy|m|h|mm|ss|hh|yyyy|dd|mm)$/;

const files = [];
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(jsx?|tsx?)$/.test(e.name)) files.push(p);
  }
})(path.join(root, "src"));

const used = {};
const re = /["'`]([a-z][a-z0-9]*(?:-[a-z0-9]+)*):([a-z0-9]+(?:-[a-z0-9]+)*)["'`]/g;
for (const f of files) {
  const rel = path.relative(path.join(root, "src"), f).replace(/\\/g, "/");
  if (!SRC_DIRS.some((d) => rel.startsWith(d + "/"))) continue;
  const src = fs.readFileSync(f, "utf8");
  let m;
  while ((m = re.exec(src))) {
    if (NOT_ICON_PREFIX.test(m[1]) || /^\d/.test(m[2])) continue;
    (used[m[1]] ||= new Set()).add(m[2]);
  }
}

const out = [];
const missing = [];
for (const [prefix, names] of Object.entries(used).sort()) {
  let set;
  try {
    set = JSON.parse(fs.readFileSync(require.resolve(`@iconify-json/${prefix}/icons.json`), "utf8"));
  } catch {
    missing.push(`${prefix} (no @iconify-json/${prefix})`);
    continue;
  }
  const icons = {};
  const aliases = {};
  const add = (n) => {
    if (set.icons[n]) icons[n] = set.icons[n];
    else if (set.aliases?.[n]) {
      aliases[n] = set.aliases[n];
      add(set.aliases[n].parent);
    } else return false;
    return true;
  };
  for (const n of [...names].sort()) if (!add(n)) missing.push(`${prefix}:${n}`);
  out.push({ prefix, icons, aliases, width: set.width, height: set.height });
}

const body = `/* AUTO-GENERATED by scripts/build-icons.mjs - do not edit. Offline icon data for @iconify/react. */
import { addCollection } from "@iconify/react/offline";

${out.map((c) => `addCollection(${JSON.stringify(c)});`).join("\n")}
`;
fs.writeFileSync(path.join(root, "src/lib/icons.generated.js"), body);
console.log(`icons: ${out.map((c) => `${c.prefix}=${Object.keys(c.icons).length}`).join(" ")}  (${(body.length / 1024).toFixed(0)} KB)`);
if (missing.length) console.log("not found / skipped:", missing.join(", "));
